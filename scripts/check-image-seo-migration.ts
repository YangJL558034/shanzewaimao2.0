import assert from "node:assert/strict";
import { localImagePath, remapImage, remapImageJson, remapRichImages, type ImageSeoManifest } from "./image-seo-migration";
const origins = new Set(["https://shanzesz.com", "http://localhost:3000"]);
const entry = { src: "/optimized/shanze-power-bank-123456abcdef.webp", width: 1600, height: 900, alt: 'Power bank "OEM" $& <view>', title: "Shanze power bank" };
const manifest: ImageSeoManifest = { "/uploads/power bank.jpg": entry, [entry.src]: entry };
assert.equal(localImagePath("https://shanzesz.com/uploads/power%20bank.jpg?v=1#x", origins), "/uploads/power bank.jpg");
assert.equal(localImagePath("https://external.example/uploads/power%20bank.jpg", origins), undefined);
assert.equal(localImagePath("//external.example/uploads/power%20bank.jpg", origins), undefined);
assert.equal(localImagePath("data:image/png;base64,123", origins), undefined);
assert.equal(localImagePath("/uploads/%5Cprivate.jpg", origins), undefined);
assert.equal(remapImage("https://shanzesz.com/uploads/power%20bank.jpg", manifest, origins), entry.src);
assert.equal(remapImage("https://external.example/uploads/power%20bank.jpg", manifest, origins), "https://external.example/uploads/power%20bank.jpg");
const html = '<p>Original text /uploads/power bank.jpg</p><a href="/uploads/power%20bank.jpg">Download original</a><img src="/uploads/power%20bank.jpg" alt="Custom user ALT" title="Custom title"><img src="/uploads/power%20bank.jpg" alt=""><img src="/uploads/power%20bank.jpg">';
const transformed = remapRichImages(html, manifest, origins);
assert.ok(transformed.includes('href="/uploads/power%20bank.jpg"'));
assert.ok(transformed.includes("Original text /uploads/power bank.jpg"));
assert.ok(transformed.includes('alt="Custom user ALT" title="Custom title"'));
assert.ok(transformed.includes('alt=""'));
assert.ok(transformed.includes('alt="Power bank &quot;OEM&quot; $&amp; &lt;view&gt;"'));
assert.equal(remapRichImages('<img src="https://external.example/img.jpg" srcset="data:image/png;base64,abc 1x, https://external.example/a.jpg 2x">', manifest, origins), '<img src="https://external.example/img.jpg" srcset="data:image/png;base64,abc 1x, https://external.example/a.jpg 2x">');
const json = JSON.stringify([{ title: "Keep title", text: "/uploads/power bank.jpg", image: "/uploads/power%20bank.jpg", href: "/uploads/power%20bank.jpg", fileUrl: "/uploads/power%20bank.jpg", alt: "User caption" }]);
const items = JSON.parse(remapImageJson(json, manifest, origins));
assert.equal(items[0].image, entry.src);
assert.equal(items[0].href, "/uploads/power%20bank.jpg");
assert.equal(items[0].fileUrl, "/uploads/power%20bank.jpg");
assert.equal(items[0].text, "/uploads/power bank.jpg");
assert.equal(items[0].alt, "User caption");
const schema = JSON.stringify({ "@type": "Product", url: "/uploads/power%20bank.jpg", image: [{ "@type": "ImageObject", url: "https://shanzesz.com/uploads/power%20bank.jpg", contentUrl: "/uploads/power%20bank.jpg", caption: "Original caption" }], logo: "/uploads/power%20bank.jpg" });
const structured = JSON.parse(remapImageJson(schema, manifest, origins, "https://shanzesz.com"));
assert.equal(structured.url, "/uploads/power%20bank.jpg");
assert.equal(structured.image[0].url, `https://shanzesz.com${entry.src}`);
assert.equal(structured.image[0].contentUrl, `https://shanzesz.com${entry.src}`);
assert.equal(structured.image[0].caption, "Original caption");
assert.equal(structured.image[0].width, entry.width);
assert.equal(structured.image[0].height, entry.height);
assert.equal(structured.logo, `https://shanzesz.com${entry.src}`);
assert.equal(remapImageJson("not json", manifest, origins), "not json");
assert.equal(remapImageJson(json, {}, origins), json);
console.log("PASS: image migration checks — local/absolute URL safety, targeted JSON/Schema/IMG updates with actual dimensions, custom ALT preservation, original download links/copy and external references unchanged.");
